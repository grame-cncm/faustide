import type { DiagramName } from "../runtime/DiagramService";

type DiagramSource = {
    readGeneratedSvg: (fileName: string, diagramName?: DiagramName) => string;
};

/**
 * Where to start a steppable diagram: the use of the diagram (a folded block
 * used at several places holds the values of each use) and the absolute
 * sample to show. Both default to the first.
 */
export type DiagramPlace = {
    use?: number;
    n?: number;
};

/** Options of `FaustSvgStep`, the player that `faust -sst` embeds in each SVG. */
type FaustSvgStepOptions = DiagramPlace & {
    onNavigate?: (target: { file: string; use: number; n: number }) => void;
};

/** What `FaustSvgStep` returns to drive the player from the page. */
export type FaustSvgStepPlayer = {
    go: (n: number) => void;
    use: (u: number) => void;
    state: () => { use: number; n: number };
};

type FaustSvgStepScope = {
    FaustSvgStep?: (svg: SVGSVGElement, options: FaustSvgStepOptions) => FaustSvgStepPlayer;
};

/**
 * Handles interactions inside the generated SVG diagram pane.
 *
 * Diagram generation remains in `DiagramService`; this view only owns DOM
 * replacement (fitted to the pane, for the first diagram and when following
 * Faust SVG links), drag-to-pan, Ctrl+wheel zoom, and the start of the player
 * that steppable diagrams (`faust -sst`) carry: values on the wires, stepping
 * keys, table of values. The player is defined by a script of the SVG and
 * started here; it hands its links back, with the use and sample to show.
 */
export class DiagramView {
    private readonly diagramSource: DiagramSource;
    private svgDragged = false;

    constructor(diagramSource: DiagramSource) {
        this.diagramSource = diagramSource;
    }

    /** Binds the three diagram interactions: link navigation, pan, and zoom. */
    bind() {
        this.bindSvgLinks();
        this.bindDragPan();
        this.bindZoom();
    }

    /**
     * Replaces the pane's content with a generated diagram, fitted to the pane
     * below its toolbar, and starts its player when the diagram is steppable.
     * Links of a steppable diagram open their target at the current sample, in
     * the diagram set recorded in `#diagram-svg[data-diagram]`.
     *
     * @param strSvg SVG source generated by Faust
     * @param place for a steppable diagram, the use and sample to show
     * @returns the inserted `<svg>` element
     */
    display(strSvg: string, place: DiagramPlace = {}) {
        const svg = $<SVGSVGElement>(strSvg).filter("svg")[0];
        const height = $("#diagram").height() - ($("#diagram-toolbar").outerHeight(true) || 0);
        const width = Math.min($("#diagram").width(), height / this.getSvgHeight(svg) * this.getSvgWidth(svg));
        $("#diagram-svg").empty().append(svg).children("svg").width(width);
        this.startPlayer(svg, place);
        return svg;
    }

    /**
     * Starts the player of a steppable diagram on its `<svg>`. Inserting the
     * SVG with jQuery has already run the player's script, which defines
     * `window.FaustSvgStep` without starting it in a page; the script is run
     * here if it was not. A page with a Content Security Policy must allow
     * inline scripts for the player to run.
     *
     * @returns the player, or `null` for a plain diagram
     */
    private startPlayer(svg: SVGSVGElement, place: DiagramPlace): FaustSvgStepPlayer | null {
        const script = svg.querySelector("script.faust-svg-step");
        if (!script) return null;
        const scope = window as unknown as FaustSvgStepScope;
        if (!scope.FaustSvgStep) {
            // Same evaluation as jQuery's: a script element added to the page.
            const run = document.createElement("script");
            run.text = script.textContent || "";
            document.head.appendChild(run).remove();
        }
        if (!scope.FaustSvgStep) return null;
        return scope.FaustSvgStep(svg, {
            use: place.use,
            n: place.n,
            onNavigate: ({ file, use, n }) => {
                if (this.svgDragged) return;
                this.display(this.diagramSource.readGeneratedSvg(file, this.diagramName()), { use, n });
            }
        });
    }

    /** Diagram set shown in the pane: `main` (process) by default. */
    private diagramName() {
        return ($("#diagram-svg").attr("data-diagram") || "main") as DiagramName;
    }

    /**
     * Follows a Faust SVG hyperlink of a plain diagram by replacing the pane
     * with the linked sub-diagram, scaled to fit. Links are read from the
     * diagram set recorded in `#diagram-svg[data-diagram]` (process by
     * default). Clicks that were part of a drag are ignored. The player of a
     * steppable diagram handles its own links and stops their clicks.
     */
    private bindSvgLinks() {
        $<SVGAElement>("#diagram-svg").on("click", "a", (e) => {
            e.preventDefault();
            if (this.svgDragged) return;
            const href = e.currentTarget.href?.baseVal || e.currentTarget.getAttribute("href");
            this.display(this.diagramSource.readGeneratedSvg(href.split("#")[0], this.diagramName()));
        });
    }

    /** Enables click-drag panning of the diagram, setting `svgDragged` so a drag does not trigger link navigation. */
    private bindDragPan() {
        $("#diagram-svg").on("mousedown", "svg", (e) => {
            e.preventDefault();
            e.stopPropagation();
            this.svgDragged = false;
            const $div = $(e.currentTarget).parent();
            const x = e.pageX;
            const y = e.pageY;
            const sL = $div.scrollLeft();
            const sT = $div.scrollTop();
            const handleMouseMove = (e: JQuery.MouseMoveEvent) => {
                if (!e.originalEvent.movementX && !e.originalEvent.movementY) return;
                this.svgDragged = true;
                const dX = e.pageX - x;
                const dY = e.pageY - y;
                $div.scrollLeft(sL - dX);
                $div.scrollTop(sT - dY);
                e.preventDefault();
                e.stopPropagation();
            };
            const handleMouseUp = (e: JQuery.MouseUpEvent) => {
                $(document).off("mousemove", handleMouseMove);
                $(document).off("mouseup", handleMouseUp);
                if (!this.svgDragged) return;
                e.preventDefault();
                e.stopPropagation();
            };
            $(document).on("mousemove", handleMouseMove);
            $(document).on("mouseup", handleMouseUp);
        });
    }

    /** Enables Ctrl+wheel zoom, scaling the SVG width by ±25% per wheel step. */
    private bindZoom() {
        $("#diagram").on("wheel", (e) => {
            if (!e.ctrlKey) return;
            const $svg = $(e.currentTarget).find("svg");
            if (!$svg.length) return;
            e.preventDefault();
            e.stopPropagation();
            const d = (e.originalEvent as WheelEvent).deltaY > 0 ? 1 : -1;
            const w = $svg.width();
            $svg.width(w * (1 - d * 0.25));
        });
    }

    /** Reads the SVG intrinsic width from the DOM value or `width` attribute. */
    private getSvgWidth(svg: SVGSVGElement) {
        return svg.width?.baseVal?.value || +svg.getAttribute("width") || 0;
    }

    /** Reads the SVG intrinsic height (defaulting to 1 to avoid division by zero). */
    private getSvgHeight(svg: SVGSVGElement) {
        return svg.height?.baseVal?.value || +svg.getAttribute("height") || 1;
    }
}
